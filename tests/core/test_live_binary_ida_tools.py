"""
tests/core/test_live_binary_ida_tools.py
========================================

Unit and integration tests for IDA FLIRT and TIL live binary analysis tools:
- match_flirt_signatures
- import_type_library
- get_struct_catalog / STRUCT_CATALOG
- CFGSignatureIndex.load_flirt_signatures
"""

import os
from pathlib import Path
import tempfile
import unittest

from superghidra.core.live_binary_tools import (
    match_flirt_signatures,
    import_type_library,
    get_struct_catalog,
    STRUCT_CATALOG,
)
from superghidra.core.parity_engine import CFGSignatureIndex
from superghidra.formats.ida_til_importer import find_ida_install


class TestLiveBinaryIdaTools(unittest.TestCase):
    """Test FLIRT signature matching and TIL type library live tools."""

    @unittest.skipUnless(
        os.path.isfile(r"E:\01_Apps\Installed\IDA_PRO\til\arm\android_arm.til"),
        "android_arm.til required",
    )
    def test_import_type_library_live(self):
        til_path = r"E:\01_Apps\Installed\IDA_PRO\til\arm\android_arm.til"
        with tempfile.NamedTemporaryFile(suffix=".h", delete=False) as tmp:
            tmp_hdr = tmp.name

        try:
            res = import_type_library(til_path, output_header=tmp_hdr)
            self.assertEqual(res["til_path"], til_path)
            self.assertGreater(res["enums_count"], 50)
            self.assertGreater(res["structs_count"], 20)
            self.assertGreater(res["typedefs_count"], 50)
            self.assertGreater(res["total_types"], 100)
            self.assertGreaterEqual(res["registered_structs"], 20)

            # Check that structs were registered into the catalog
            catalog = get_struct_catalog()
            self.assertGreaterEqual(len(catalog), 20)

            # Check exported header
            self.assertTrue(os.path.isfile(tmp_hdr))
            self.assertGreater(os.path.getsize(tmp_hdr), 1000)
            with open(tmp_hdr, "r", encoding="utf-8") as f:
                content = f.read()
                self.assertIn("Generated by SuperGhidra IDA TIL Importer", content)
        finally:
            if os.path.exists(tmp_hdr):
                try:
                    os.remove(tmp_hdr)
                except OSError:
                    pass

    @unittest.skipUnless(
        os.path.isfile(r"E:\01_Apps\Installed\IDA_PRO\sig\pc\bc31cls.sig"),
        "bc31cls.sig required",
    )
    def test_cfg_signature_index_load_flirt(self):
        sig_path = r"E:\01_Apps\Installed\IDA_PRO\sig\pc\bc31cls.sig"
        idx = CFGSignatureIndex()
        count = idx.load_flirt_signatures(sig_path)
        self.assertGreater(count, 50)
        self.assertIsNotNone(idx.flirt_index)

        # Match known Borland prologue
        code = bytes.fromhex("558BEC56578B46060B46087514B8080050AABBCCDDEE598956088946060BC274")
        sym = idx.match_flirt(code)
        self.assertIsNotNone(sym)
        self.assertIn("VectorImp", sym)

    @unittest.skipUnless(
        os.path.isfile(r"E:\01_Apps\Installed\IDA_PRO\ida.dll")
        and os.path.isfile(r"E:\01_Apps\Installed\IDA_PRO\sig\pc\bc31cls.sig"),
        "ida.dll and bc31cls.sig required",
    )
    def test_match_flirt_signatures_live(self):
        bin_path = r"E:\01_Apps\Installed\IDA_PRO\ida.dll"
        sig_path = r"E:\01_Apps\Installed\IDA_PRO\sig\pc\bc31cls.sig"

        res = match_flirt_signatures(bin_path, sig_path=sig_path)
        self.assertIn("binary_path", res)
        self.assertIn("total_patterns", res)
        self.assertIn("matched_count", res)
        self.assertIn("matches", res)
        self.assertIn("matched_functions", res)
        self.assertGreater(res["total_patterns"], 50)

    @unittest.skipUnless(
        os.path.isfile(r"E:\01_Apps\Installed\IDA_PRO\ida.dll"),
        "ida.dll required",
    )
    def test_match_flirt_signatures_default_sig_discovery(self):
        bin_path = r"E:\01_Apps\Installed\IDA_PRO\ida.dll"
        # Let it discover sigs automatically from find_ida_install() / sig/
        res = match_flirt_signatures(bin_path, sig_path=None)
        self.assertIn("binary_path", res)
        self.assertIn("total_patterns", res)
        self.assertIn("matched_count", res)
        self.assertGreater(res["total_patterns"], 0)


if __name__ == "__main__":
    unittest.main()
